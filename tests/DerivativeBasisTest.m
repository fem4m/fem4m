    methods (Test)

        function testDerivativeBasis(testCase,derivative)
            mesh = FormBasisTest.meshFor(derivative.field);
            fe = derivative.space(mesh);
            ref = DerivativeBasisTest.refPoint(mesh);
            pts = mesh.point4e(ref);
            x = FormValueTest.coefficients(fe,derivative.field);

            val = DerivativeBasisTest.contract(fe,derivative.method,pts,ref,x);

            expected = derivative.L(FormValueTest.evalField(derivative.field,pts));
            % the higher derivatives on the small elements lose digits
            testCase.verifyEqual(val(:,1:size(expected,2)),expected, ...
                'AbsTol',DerivativeBasisTest.relTol(testCase,derivative)*max(1,max(abs(expected(:)))), ...
                'derivatives of the polynomial');
            testCase.verifyEqual(val(:,size(expected,2)+1:end), ...
                zeros(mesh.nrElems,size(val,2)-size(expected,2)),'unused components');
        end

        function testBiharmonicValue(testCase,biharmonic)
            mesh = FormBasisTest.meshFor(biharmonic.field);
            fe = biharmonic.space(mesh);
            ref = DerivativeBasisTest.refPoint(mesh);
            pts = mesh.point4e(ref);
            x = FormValueTest.coefficients(fe,biharmonic.field);

            val = fe.getBiharmonicValue(pts,ref,1:mesh.nrElems,x);

            F = FormValueTest.evalField(biharmonic.field,pts);
            testCase.verifyEqual(val,F.bih, ...
                'AbsTol',DerivativeBasisTest.relTol(testCase,biharmonic)*max(abs(F.bih)));
        end

        function testRigidBodyDerivatives(testCase)
            mesh = PatchTestCase.patchMesh(struct('name','Lshape'));
            fe = RBM(1,mesh);
            ref = DerivativeBasisTest.refPoint(mesh);
            pts = mesh.point4e(ref);
            x = fe.project(@(z)[1 - 2*z(:,2), 3 + 2*z(:,1)]);
            nrElems = mesh.nrElems;

            grad = DerivativeBasisTest.contract(fe,'getGradBasis',pts,ref,x);
            symGrad = DerivativeBasisTest.contract(fe,'getSymGradBasis',pts,ref,x);
            d2 = DerivativeBasisTest.contract(fe,'getD2Basis',pts,ref,x);

            % J(i,j) = d_j u_i column by column
            testCase.verifyEqual(grad,repmat([0 2 -2 0],nrElems,1),'AbsTol',testCase.tol,'gradient');
            testCase.verifyEqual(symGrad,zeros(nrElems,3),'symmetric gradient');
            testCase.verifyEqual(d2,zeros(nrElems,3),'second derivatives');
        end

        function testBubbleDerivatives(testCase,bubble,bubbleMethod)
            mesh = PatchTestCase.patchMesh(struct('name','Lshape'));
            fe = bubble(mesh);
            dg = DGDk(fe.degree,mesh);
            ref = DerivativeBasisTest.refPoint(mesh);
            pts = mesh.point4e(ref);
            x = sin(1:fe.nrDoF)';
            xDG = dg.project(@(p,r,ind)fe.getValue(p,r,ind,x));

            val = DerivativeBasisTest.contract(fe,bubbleMethod,pts,ref,x);

            expected = DerivativeBasisTest.contract(dg,bubbleMethod,pts,ref,xDG);
            testCase.verifyEqual(val,expected,'AbsTol',testCase.tol*max(1,max(abs(expected(:)))));
        end

    end

    methods (Static)

        function tol = relTol(testCase,param)
            %relTol - Relative tolerance of a parameter, tol by default
            %   The fourth derivatives of the TUBA basis, whose
            %   coefficients include scaled Hessian degrees of freedom,
            %   lose more digits on the small elements.
            if isfield(param,'relTol')
                tol = param.relTol;
            else
                tol = testCase.tol;
            end
        end

        function ref = refPoint(mesh)
            %refPoint - Interior reference point of the elements
            ref = [0.2 0.3 0.1];
            ref = ref(1:size(mesh.c4n,2));
        end

        function val = contract(fe,method,pts,ref,x)
            %contract - Contract a basis with the coefficients X
            %   VAL is nrElems x nrComponents.
            nrElems = fe.mesh.nrElems;
            basis = FormBasis.elementRows(fe.(method)(pts,ref,1:nrElems),1:nrElems,fe);
            val = reshape(sum(basis.*x(fe.dof4e),2),nrElems,[]);
        end

