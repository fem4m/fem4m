        function verifyCoverage(testCase,className)
            %verifyCoverage - Every side operator is tested on edges and faces
            %   Every side operator (suffix _S) of the class CLASSNAME
            %   must be tested on edges (edgeOp, or the expected error of
            %   faceOnlyOp) and on faces (faceOp, or the expected error of
            %   edgeOnlyOp) of the test class of CLASSNAME.
            ops = methods(className);
            ops = ops(endsWith(ops,'_S'));
            testClass = [className,'Test'];
            onEdges = [FormBasisTest.parameterOps(testClass,'edgeOp'), ...
                FormBasisTest.parameterOps(testClass,'faceOnlyOp')];
            onFaces = [FormBasisTest.parameterOps(testClass,'faceOp'), ...
                FormBasisTest.parameterOps(testClass,'edgeOnlyOp')];
            testCase.verifyEmpty(setdiff(ops,onEdges),'side operators not tested on edges');
            testCase.verifyEmpty(setdiff(ops,onFaces),'side operators not tested on faces');
        end

        function ops = parameterOps(testClass,name)
            %parameterOps - Operator names of a test parameter of a test class
            mc = meta.class.fromName(testClass);
            params = mc.PropertyList(strcmp({mc.PropertyList.Name},name)).DefaultValue;
            ops = cellfun(@(f)params.(f).op,fieldnames(params)','UniformOutput',false);
        end

        function verifySideOperator(testCase,sideOp)
            %verifySideOperator - Verify an edge or face operator
            mesh = FormBasisTest.meshFor(sideOp.field);
            fe = sideOp.space(mesh);
            [ref,pts,n,t,e4s] = FormBasisTest.sideGeometry(mesh);
            nrSides = size(e4s,1);
            nrBasisFunc = fe.nrBasisFunc;
            inner = e4s(:,2) > 0;
            s = sideOp.dg*(1:mesh.nrElems)'/mesh.nrElems;
            s1 = s(e4s(:,1));
            s2 = zeros(nrSides,1);
            s2(inner) = s(e4s(inner,2));
            x = FormBasisTest.coefficients(fe,sideOp.field);
            c = (1+s1).*x(fe.dof4e(e4s(:,1),:));
            factor = 1 + s1;
            twoSided = startsWith(sideOp.op,{'jump','average'});
            if twoSided
                c2 = zeros(nrSides,nrBasisFunc);
                c2(inner,:) = (1+s2(inner)).*x(fe.dof4e(e4s(inner,2),:));
                c = [c,c2];
                if startsWith(sideOp.op,'jump')
                    factor(inner) = s1(inner) - s2(inner);
                else
                    factor(inner) = 1 + (s1(inner) + s2(inner))/2;
                end
            end

            val = FormBasis.(sideOp.op)(pts,ref,1:nrSides,fe);

            testCase.assertEqual(size(val,[1 2]),[nrSides,size(c,2)],'size');
            F = FormBasisTest.evalField(sideOp.field,pts);
            testCase.verifyEqual(FormBasisTest.contract(val,c), ...
                factor.*sideOp.L(F,n,t),'AbsTol',testCase.tol,'operator of the polynomial');
            if twoSided
                side2 = val(~inner,nrBasisFunc+1:end,:);
                testCase.verifyLessThanOrEqual(max(abs(side2(:))),testCase.tol, ...
                    'no second side on the boundary');
            end
            parts = nrSides:-2:1;
            valParts = FormBasis.(sideOp.op)(pts(parts,:),ref,parts,fe);
            testCase.verifyEqual(valParts(:,:),val(parts,:),'AbsTol',testCase.tol,'subset of sides');
        end

        function mesh = meshFor(field)
            %meshFor - L-shaped 2d patch mesh or 3d cube mesh of the field
            if endsWith(field,'3d')
                mesh = UnitTestCase.cubeMesh();
            else
                mesh = PatchTestCase.patchMesh(struct('name','Lshape'));
            end
        end

        function [ref,pts,n,t,e4s] = sideGeometry(mesh)
            %sideGeometry - Points, unit normals and tangents of the sides
            %   The normals point out of the first neighboring element and
            %   the 2d tangents are the normals rotated counterclockwise.
            c4n = mesh.c4n;
            if isa(mesh,'Mesh3d')
                ref = [0.2 0.3];
                pts = mesh.point4f(ref);
                e4s = mesh.e4f;
                n4s = mesh.n4f;
                n = cross(c4n(n4s(:,2),:)-c4n(n4s(:,1),:),c4n(n4s(:,3),:)-c4n(n4s(:,1),:),2);
            else
                ref = 0.3;
                pts = mesh.point4ed(ref);
                e4s = mesh.e4ed;
                n4s = mesh.n4ed;
                tau = c4n(n4s(:,2),:) - c4n(n4s(:,1),:);
                n = [tau(:,2),-tau(:,1)];
            end
            n = n./vecnorm(n,2,2);
            n4e = mesh.n4e(e4s(:,1),:);
            mid = permute(mean(reshape(c4n(n4e(:),:),size(n4e,1),size(n4e,2),[]),2),[1 3 2]);
            n = n.*sign(sum((pts-mid).*n,2));
            t = [-n(:,2),n(:,1),zeros(size(n,1),size(n,2)-2)];
        end

        function x = coefficients(fe,field)
            %coefficients - Coefficients of the polynomial field in FE
            %   The L2 projection reproduces the polynomial field, for the
            %   vector and matrix elements component by component.
            if isa(fe,'FEVector')
                x = [];
                for k = 1 : numel(fe.fe)
                    x = [x;fe.fe{k}.project(@(z)FormBasisTest.fieldValue(field,z,'s',k))]; %#ok<AGROW>
                end
            elseif startsWith(field,'symmatrix')
                x = fe.project(@(z)FormBasisTest.fieldValue(field,z,'M'));
            else
                x = fe.project(@(z)FormBasisTest.fieldValue(field,z,'s'));
            end
        end

        function val = fieldValue(field,z,name,k)
            %fieldValue - Value F.(NAME) of the field, or its k-th column
            F = FormBasisTest.evalField(field,z);
            val = F.(name);
            if nargin > 3
                val = val(:,k);
            end
        end

        function F = evalField(field,z)
            %evalField - Polynomial field and its derivatives at points z
            %   F.v is the value, F.g the gradient, F.H the Hessian,
            %   F.gradLaplace the gradient of the Laplacian and F.curl the
            %   2d curl (d_y v, -d_x v) of a scalar field, F.J the Jacobian
            %   (J(i,j) = d_j v_i), F.div the (row) divergence, F.rot the
            %   2d rot d_x v_2 - d_y v_1 and F.curl the 3d curl of a vector
            %   field, and F.M the matrix and F.rowRot the row-wise rot of a
            %   2d matrix field, all matrices as nrPts x dim x dim arrays.
            %   F.s holds the stored components. F.curlrot is the
            %   curl(rot(v)) and F.lap the vector Laplacian of the 2d vector
            %   field, F.curlcurl the curl-curl of the quadratic 3d vector
            %   field vectorquad3d, which also has its vector Laplacian F.lap
            %   and F.graddiv = grad(div v), its divergence F.div and curl
            %   F.curl, and F.rotrot the rot(rot(sigma)), F.divdiv the
            %   div(div(sigma)) and F.lap the Laplacians of the stored
            %   components of the quadratic symmetric matrix field
            %   symquad2d, which symmatrixquad2d gives as matrices. The cubic 3d vector field
            %   vectorcubic3d has its divergence F.div and curl F.curl. The
            %   3d symmetric matrix fields symmatrix3d and symquad3d have
            %   their row divergence F.div, the quadratic one also its
            %   double divergence F.divdiv. The non-symmetric quadratic
            %   matrix fields matrixquad2d and matrixquad3d have their double
            %   divergence F.divdiv.
            x = z(:,1);
            y = z(:,2);
            o = ones(size(x));
            switch field
                case 'scalar2d'
                    F.v = x.^3 - 2*x.*y.^2 + y + 1;
                    F.g = [3*x.^2 - 2*y.^2, -4*x.*y + 1];
                    F.H = FormBasisTest.symmetric([6*x, -4*x, -4*y]);
                    F.gradLaplace = [2*o, 0*o];
                    F.curl = [F.g(:,2), -F.g(:,1)];
                    F.s = F.v;
                case 'vector2d'
                    F.v = [x.^2 - y + 1, x.*y + 2*y.^2 - x];
                    F.J = reshape([2*x, y - 1, -o, x + 4*y],[],2,2);
                    F.div = 3*x + 4*y;
                    F.rot = y;
                    F.curlrot = o*[1 0];
                    F.lap = o*[2 4];
                    F.s = F.v;
                case 'symmatrix2d'
                    F.s = [x + 1, x + 2*y, x - 2*y];
                    F.M = FormBasisTest.symmetric(F.s);
                    F.div = [-o, 3*o];
                    F.rowRot = o*[1 3];
                case {'symquad2d','symmatrixquad2d'}
                    F.s = [x.^2 + y.^2, x.*y + y.^2, x.^2 - 3*x.*y];
                    F.M = FormBasisTest.symmetric(F.s);
                    F.rotrot = 8*o;
                    F.divdiv = -2*o;
                    F.lap = o*[4 2 2];
                case 'matrix2d'
                    F.s = [x + 1, x - y, 2*y, y + 2];
                    F.M = reshape(F.s,[],2,2);
                    F.div = o*[3 2];
                    F.rowRot = o*[0 1];
                case 'matrixquad2d'
                    F.s = [x.^2 + y.^2, x.*y - y.^2, 3*x.*y + x.^2, x.^2 - 2*y.^2];
                    F.M = reshape(F.s,[],2,2);
                    F.divdiv = 2*o;
                case 'scalar3d'
                    z = z(:,3);
                    F.v = x.^3 - 2*x.*y.*z + y.^2 - 3*z.^2 + z + 1;
                    F.g = [3*x.^2 - 2*y.*z, -2*x.*z + 2*y, -2*x.*y - 6*z + 1];
                    F.H = FormBasisTest.symmetric([6*x, 2*o, -6*o, -2*z, -2*y, -2*x]);
                    F.gradLaplace = [6*o, 0*o, 0*o];
                    F.s = F.v;
                case 'vector3d'
                    z = z(:,3);
                    F.v = [1 + x - 2*y + 2*z, 2*x + y - z, x - 2*y + 3*z + 1];
                    F.J = reshape(o*[1 2 1 -2 1 -2 2 -1 3],[],3,3);
                    F.div = 5*o;
                    F.curl = o*[-1 1 4];
                    F.s = F.v;
                case 'vectorquad3d'
                    z = z(:,3);
                    F.v = [x.^2 + y.^2, x.*z + y.^2, x.^2 + x.*y];
                    F.lap = o*[4 2 2];
                    F.graddiv = o*[2 2 0];
                    F.curlcurl = F.graddiv - F.lap;
                    F.div = 2*x + 2*y;
                    F.curl = [0*o, -2*x - y, z - 2*y];
                    F.s = F.v;
                case 'vectorcubic3d'
                    z = z(:,3);
                    F.v = [x.^3 + y.*z.^2, x.*y.*z + y.^3, x.^2.*y + z.^3];
                    F.div = 3*x.^2 + x.*z + 3*y.^2 + 3*z.^2;
                    F.curl = [x.^2 - x.*y, 2*y.*z - 2*x.*y, y.*z - z.^2];
                    F.s = F.v;
                case 'symmatrix3d'
                    F.s = (1:6) + x - (1:6).*y + z(:,3);
                    F.M = FormBasisTest.symmetric(F.s);
                    F.div = o*[-2 0 -4];
                case 'symquad3d'
                    z = z(:,3);
                    F.s = [x.^2 + y.*z, 3*y.^2 - x.*z, x.*y - z.^2, ...
                        2*x.*y + z.^2, y.^2 - x.*z, 5*y.*z + x.^2];
                    F.M = FormBasisTest.symmetric(F.s);
                    F.div = [3*x, 13*y, 2*z];
                    F.divdiv = 18*o;
                case 'matrix3d'
                    F.s = (1:9) + x - (1:9).*y + z(:,3);
                    F.M = reshape(F.s,[],3,3);
                    F.div = o*[-2 -3 -4];
                case 'matrixquad3d'
                    z = z(:,3);
                    F.s = [x.^2 + y.*z, x.*y + z.^2, x.*z - y.^2, ...
                        2*x.*y - z.^2, y.^2 + x.*z, y.*z + x.^2, ...
                        3*x.*z, x.^2 - y.*z, z.^2 - x.*y];
                    F.M = reshape(F.s,[],3,3);
                    F.divdiv = 13*o;
            end
        end

        function M = symmetric(s)
            %symmetric - Symmetric matrices from the stored components
            %   The components are [11 22 12] in 2d and [11 22 33 12 13 23]
            %   in 3d.
            if size(s,2) == 3
                M = reshape(s(:,[1 3 3 2]),[],2,2);
            else
                M = reshape(s(:,[1 4 5 4 2 6 5 6 3]),[],3,3);
            end
        end

        function s = symflat(M)
            %symflat - Stored components [11 22 12] or [11 22 33 12 13 23]
            if size(M,2) == 2
                s = M(:,[1 4 3]);
            else
                s = M(:,[1 5 9 4 7 8]);
            end
        end

        function s = flat(M)
            %flat - Matrices column by column
            s = reshape(M,size(M,1),[]);
        end

        function S = sym(M)
            %sym - Symmetric part of the matrices
            S = (M + permute(M,[1 3 2]))/2;
        end

        function C = rowCurl(J)
            %rowCurl - Row-wise 2d curls (d_y v_i, -d_x v_i) of the Jacobians
            C = cat(3,J(:,:,2),-J(:,:,1));
        end

        function val = tr(M)
            %tr - Traces of the matrices
            d = size(M,2);
            val = sum(M(:,1:d+1:d^2),2);
        end

        function val = cof(H)
            %cof - Cofactor matrices [yy -xy -xy xx] of 2d Hessians
            val = [H(:,2,2), -H(:,1,2), -H(:,2,1), H(:,1,1)];
        end

        function val = mv(M,n)
            %mv - Matrix-vector products M*n
            val = sum(M.*permute(n,[1 3 2]),3);
        end

        function val = nmm(n,M,m)
            %nmm - Bilinear forms n'*M*m
            val = sum(n.*FormBasisTest.mv(M,m),2);
        end

        function M = outer(v,n)
            %outer - Outer products v*n' column by column
            M = FormBasisTest.flat(v.*permute(n,[1 3 2]));
        end

        function val = contract(val,c)
            %contract - Contract basis values with local coefficients
            val = reshape(sum(val.*c,2),size(val,1),[]);
        end

    end

