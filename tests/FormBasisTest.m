    %   Every operator of FormBasis is applied to the basis of a finite
    %   element space that contains a polynomial field f and contracted
    %   with the coefficients of f, which gives the operator applied to f
    %   at the physical point. The operators are evaluated at one
    %   reference point of all elements, edges or faces, as integrate
    %   passes a quadrature point. The side operators are contracted with
    %   the coefficients of the first neighboring element, and the jumps
    %   and averages with those of both neighbors, as in
    %   BilinearForm.assemble. Normals and tangents are those of the first
    %   neighboring element.
    %
    %   In the discontinuous spaces the field is scaled by 1 + s_T with
    %   s_T = T/nrElems on the element T, so that the jump is (s_1 - s_2)
    %   times the operator and the average 1 + (s_1 + s_2)/2 times it,
    %   while both are the one-sided value on the boundary. In the
    %   conforming spaces the jump of the continuous quantity vanishes on
    %   interior sides. The values of the missing second neighbor of
    %   boundary sides vanish, and operators evaluated on a subset of the
    %   sides give the corresponding rows.
    %
    %   The operators wn_T and devw_T and the trace basis branch of trw_T
    %   call element functions that no element implements and are not
    %   tested.
    %
    %   See also FormBasis, BilinearForm, UnitTestCase

