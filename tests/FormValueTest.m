    %   Every operator of FormValue is applied to the coefficients of a
    %   polynomial field f in a finite element space that contains it, which
    %   gives the operator applied to f at the physical point. As
    %   ErrorForm and EstimatorForm do, the operators are evaluated at one
    %   reference point of all elements, edges or faces. Normals and
    %   tangents are those of the first neighboring element, and the
    %   coefficient arguments are the identity unless an elasticity tensor
    %   with the Lame parameters lambda = 2 and mu = 3 is given.
    %
    %   In the discontinuous spaces the field is scaled by 1 + s_T with
    %   s_T = T/nrElems on the element T, so that the jump is (s_1 - s_2)
    %   times the operator, the average 1 + (s_1 + s_2)/2 times it and the
    %   one-sided operators 1 + s_1 times it, while jumps and averages are
    %   the one-sided value on the boundary. In the conforming spaces the
    %   jump of the continuous quantity vanishes on interior sides.
    %   Operators evaluated on a subset of the elements or sides give the
    %   corresponding rows. Jumps of normal derivatives assembled by
    %   ErrorForm and EstimatorForm are the sums of the squared jumps over
    %   the interior sides.
    %
    %   The operator wn_T calls an element function that no element
    %   implements and is not tested.
    %
    %   See also FormValue, ErrorForm, EstimatorForm, FormBasisTest,
    %   UnitTestCase

