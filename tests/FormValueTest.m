        function testElementOperator(testCase,elementOp)
            mesh = FormBasisTest.meshFor(elementOp.field);
            fe = elementOp.space(mesh);
            ref = [0.2 0.3 0.1];
            ref = ref(1:size(mesh.c4n,2));
            pts = mesh.point4e(ref);
            x = FormValueTest.coefficients(fe,elementOp.field);
            args = FormValueTest.extraArguments(elementOp);

            val = FormValue.(elementOp.op)(pts,ref,1:mesh.nrElems,x,fe,args{:});

            nrElems = mesh.nrElems;
            F = FormValueTest.evalField(elementOp.field,pts);
            expected = reshape(elementOp.L(F),nrElems,[]);
            % the fourth derivatives on the small elements lose digits
            testCase.verifyEqual(reshape(val,nrElems,[]),expected, ...
                'AbsTol',testCase.tol*max(1,max(abs(expected(:)))),'operator of the polynomial');
            parts = nrElems:-2:1;
            valParts = FormValue.(elementOp.op)(pts(parts,:),ref,parts,x,fe,args{:});
            testCase.verifyEqual(reshape(valParts,numel(parts),[]), ...
                reshape(val(parts,:),numel(parts),[]),'AbsTol',testCase.tol,'subset of elements');
        end

