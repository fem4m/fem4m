        function testErrorFormJumps(testCase)
            mesh = PatchTestCase.patchMesh(struct('name','Lshape'));
            [weight,inner] = FormValueTest.interiorEdges(mesh);
            n = mesh.normal4ed;

            % gradient jump of the elementwise scaled u = x + 2y
            [x,fe,jump] = FormValueTest.scaledField(mesh,@(m)DGPk(1,m),@(p)p(:,1) + 2*p(:,2));
            expected = jump.*(n(:,1) + 2*n(:,2));
            FormValueTest.verifyJumpForms(testCase,'([grad(u)]*n)^2 dsi',x,fe, ...
                weight,inner,expected);

            % jump of the second normal derivative of u = x^2 + 3xy
            [x,fe,jump] = FormValueTest.scaledField(mesh,@(m)DGPk(2,m), ...
                @(p)p(:,1).^2 + 3*p(:,1).*p(:,2));
            expected = jump.*(2*n(:,1).^2 + 6*n(:,1).*n(:,2));
            FormValueTest.verifyJumpForms(testCase,'([D2(u)*n*n])^2 dsi',x,fe, ...
                weight,inner,expected);
        end

