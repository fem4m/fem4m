        function mesh = unionJackMesh()
            %unionJackMesh - Unit square of eight triangles at the centre
            %   The eight right triangles of the Union Jack mesh have
            %   different orientations and vertex orders; the bottom edge
            %   is Dirichlet and the others are Neumann boundary.
            c4n = [0 0;1 0;1 1;0 1;0.5 0;1 0.5;0.5 1;0 0.5;0.5 0.5];
            n4e = [1 5 9;1 9 8;5 2 9;2 6 9;6 3 9;3 7 9;7 4 9;4 8 9];
            mesh = Mesh(c4n,n4e,[1 5;5 2],[2 6;6 3;3 7;7 4;4 8;8 1]);
        end

        function f = field(type,degree,dim)
            %field - Polynomial or smooth field of the given type
            %   F(Z) returns the field at the physical points Z as rows,
            %   matrices column by column. The components c = 0,1,... of
            %   degree k are (1 + x - 2y + z + c*y)^k + c with z = 0 in 2d,
            %   and the smooth components are sin(1 + x - 2y + z + c*y) + c.
            %   Rigid body motions are (1 - 2y, 3 + 2x).
            switch type
                case 'scalar'
                    nrComps = 1;
                case 'vector'
                    nrComps = dim;
                case {'symmatrix','matrix'}
                    nrComps = dim^2;
                case 'rigid'
                    f = @(z)[1 - 2*z(:,2), 3 + 2*z(:,1)];
                    return
            end
            c = 0 : nrComps-1;
            if strcmp(type,'symmatrix')
                % symmetric: entry (i,j) uses the component of (min,max)
                [i,j] = ndgrid(1:dim);
                c = c(sub2ind([dim dim],min(i(:),j(:))',max(i(:),j(:))'));
            end
            if dim == 2
                arg = @(z)1 + z(:,1) - 2*z(:,2) + c.*z(:,2);
            else
                arg = @(z)1 + z(:,1) - 2*z(:,2) + z(:,3) + c.*z(:,2);
            end
            if strcmp(degree,'smooth')
                f = @(z)sin(arg(z)) + c;
            else
                f = @(z)arg(z).^degree + c;
            end
        end

        function val = stored(fe,val)
            %stored - Components of matrix fields as stored by FE
            %   Symmetric matrix elements store [11 22 12] in 2d and
            %   [11 22 33 12 13 23] in 3d, all others the full matrices
            %   column by column.
            basis = fe.getBasis([],zeros(1,size(fe.mesh.c4n,2)),[]);
            if size(basis,3) == 3 && size(val,2) == 4
                val = val(:,[1 4 3]);
            elseif size(basis,3) == 6 && size(val,2) == 9
                val = val(:,[1 5 9 4 7 8]);
            end
        end

