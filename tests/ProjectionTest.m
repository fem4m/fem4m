    %ProjectionTest - Unit tests of the L2 projection
    %   The projection FE.project solves the local L2 projection on every
    %   element for a function of the physical points, or of the points,
    %   reference points and element indices, and averages the values of
    %   shared degrees of freedom. It reproduces every polynomial field
    %   the space contains, which is checked for all finite elements at
    %   interior reference points against the largest full polynomial
    %   space they contain, and for RBM against the rigid body motions. In the discontinuous spaces it is
    %   the L2 projection, i.e. M*x = b for the mass matrix 'u*v dx' and
    %   the load vector 'f(x)*v dx' of a smooth non-polynomial function,
    %   and it reproduces elementwise polynomials with a different scaling
    %   on every element. The projection of a finite element function
    %   given by its getValue into a space that contains it reproduces it.
    %   In the hp spaces with elementwise degrees the projection has
    %   allnrDoF coefficients, and the degrees of freedom that no element
    %   uses (nonDoFNodes, also those of elements of degree 0 in DGDk and
    %   of degree 3 in Bk) are exactly zero. Vector-valued elements carry
    %   the unused dofs of their components, which are shifted by their
    %   allnrDoF, and CurlBRotk those of its own numbering, so that the
    %   used dofs of DGDkVector, DGDkMatrix, a vector of Bk, the Mini
    %   element, CurlBRotk and FEMatrix + CurlBRotk with elementwise
    %   degrees are distinct and the projection of a function of the
    %   space reproduces it. With elementwise degrees 4 to
    %   6 they reproduce P4, and the projection of a function of the space
    %   on a coarse mesh onto the space on its red-green-blue refinement,
    %   whose elements inherit the degrees of their parents, reproduces
    %   the function (the prolongation is exact).
    %   The reduced Arnold-Winther element AW0 reproduces a cubic field
    %   whose divergence is a rigid motion, also on the Union Jack mesh of
    %   eight right triangles in different orientations and vertex orders.
    %   The projections of boundary data, the normal trace of RTk and BDMk
    %   (and row by row of FEMatrix) on the Neumann boundary and the
    %   normal-normal trace of HHJk on given boundary edges, give the
    %   degrees of freedom of the projection of the field on these edges
    %   and zero elsewhere.
    %
    %   See also FE, FEVector, UnitTestCase

