        function verifyValues(testCase,fe,x,g)
            %verifyValues - Verify the projection against g at points
            %   The coefficients X of FE are contracted with the basis at
            %   interior reference points and compared with the stored
            %   components returned by the function G of the reference
            %   coordinates. Vertices are avoided since the higher order
            %   bases of RTk and Nd1k are not defined there.
            dim = size(fe.mesh.c4n,2);
            refPoints = [0.2 0.3 0.1;0.6 0.1 0.2;0.25 0.25 0.25];
            for ref = refPoints(:,1:dim)'
                basis = fe.getBasis([],ref',[]);
                val = reshape(sum(basis.*x(fe.dof4e),2),fe.mesh.nrElems,[]);
                testCase.verifyEqual(val,g(ref'),'AbsTol',testCase.tol, ...
                    sprintf('values at the reference point %s',mat2str(ref')));
            end
        end

        function val = valueInParent(fe,x,pts,parents)
            %valueInParent - Value of a finite element function at points
            %   The function of the 2d space FE with coefficients X is
            %   evaluated at the physical points PTS (rows) in the elements
            %   PARENTS of FE.mesh, one column per component. The basis is
            %   evaluated once for every reference point the points map to.
            n4e = fe.mesh.n4e(parents,:);
            c4n = fe.mesh.c4n;
            a = c4n(n4e(:,1),:);
            e1 = c4n(n4e(:,2),:) - a;
            e2 = c4n(n4e(:,3),:) - a;
            d = pts - a;
            area = e1(:,1).*e2(:,2) - e1(:,2).*e2(:,1);
            ref = [d(:,1).*e2(:,2) - d(:,2).*e2(:,1), e1(:,1).*d(:,2) - e1(:,2).*d(:,1)]./area;
            [refPts,~,group] = uniquetol(ref,1e-12,'ByRows',true);
            val = zeros(size(pts,1),0);
            for k = 1 : size(refPts,1)
                ind = group == k;
                basis = fe.getBasis([],refPts(k,:),[]);
                basis = reshape(basis,size(basis,1),size(basis,2),[]);
                xe = reshape(x(fe.dof4e(parents(ind),:)),nnz(ind),[]);
                val(ind,1:size(basis,3)) = reshape(sum(basis(parents(ind),:,:).*xe,2),nnz(ind),[]);
            end
        end

