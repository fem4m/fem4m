    methods (Test)

        function testReproducesPolynomial(testCase,element)
            mesh = ProjectionTest.mesh(element.dim);
            fe = element.space(mesh);
            f = ProjectionTest.field(element.field,element.degree,element.dim);

            x = fe.project(f);

            ProjectionTest.verifyValues(testCase,fe,x,@(z)ProjectionTest.stored(fe,f(mesh.point4e(z))));
        end

        function testElementwisePolynomial(testCase,dgElement)
            mesh = ProjectionTest.mesh(dgElement.dim);
            fe = dgElement.space(mesh);
            f = ProjectionTest.field(dgElement.field,dgElement.degree,dgElement.dim);
            scale = 1 + (1:mesh.nrElems)'/mesh.nrElems;

            x = fe.project(@(pts,ptsref,ind)scale(ind).*f(pts));

            ProjectionTest.verifyValues(testCase,fe,x,@(z)scale.*ProjectionTest.stored(fe,f(mesh.point4e(z))));
        end

        function testL2Projection(testCase,dgElement)
            mesh = ProjectionTest.mesh(dgElement.dim);
            fe = dgElement.space(mesh);
            f = ProjectionTest.field(dgElement.field,'smooth',dgElement.dim);

            x = fe.project(f);

            M = BilinearForm('u*v dx').assemble(fe);
            b = LinearForm('f(x)*v dx').assemble(fe,'f',f);
            testCase.verifyEqual(M*x,b,'AbsTol',testCase.tol,'M*x = b');
        end

        function testProjectsFunction(testCase,feFunction)
            mesh = ProjectionTest.mesh(feFunction.dim);
            source = feFunction.source(mesh);
            target = feFunction.target(mesh);
            xSource = sin(1:source.nrDoF)';

            x = target.project(@(pts,ptsref,ind)source.getValue(pts,ptsref,ind,xSource));

            ProjectionTest.verifyValues(testCase,target,x, ...
                @(z)reshape(source.getValue([],z,[],xSource),mesh.nrElems,[]));
        end

        function testUnusedDegreesOfFreedom(testCase,hpElement)
            mesh = ProjectionTest.mesh(2);
            fe = hpElement(mesh);
            unused = fe.nonDoFNodes;
            testCase.assertNotEmpty(unused,'elements of lower degree');
            testCase.assertEqual(numel(unused),fe.allnrDoF - fe.nrDoF,'number of unused dofs');

            x = fe.project(@(z)sin(1 + z(:,1) - 2*z(:,2)));

            testCase.verifySize(x,[fe.allnrDoF 1]);
            testCase.verifyEqual(x(unused),zeros(numel(unused),1),'unused dofs are zero');
            used = setdiff(1:fe.allnrDoF,unused);
            testCase.verifyTrue(all(isfinite(x(used))) && any(x(used) ~= 0),'used dofs');
        end

        function testElementwiseRenumbering(testCase,hpRenumbered)
            % renumbered dofs of elementwise degrees: the components of
            % vector elements are shifted by their allnrDoF, and CurlBRotk
            % numbers one dof less per element than its DGDk
            mesh = ProjectionTest.mesh(2);
            fe = hpRenumbered(mesh);
            unused = fe.nonDoFNodes;
            testCase.assertNotEmpty(unused,'elements of lower degree');
            testCase.verifyEqual(numel(unused),fe.allnrDoF - fe.nrDoF,'number of unused dofs');
            testCase.verifyEqual(max(fe.dof4e(:)),fe.allnrDoF,'all dofs');
            testCase.verifyEqual(numel(setdiff(fe.dof4e(:),unused)),fe.nrDoF,'distinct used dofs');
            testCase.verifyEmpty(intersect(fe.freeNodes,unused),'free dofs');
            xFE = sin(1:fe.allnrDoF)';
            xFE(unused) = 0;

            x = fe.project(@(pts,ptsref,ind)fe.getValue(pts,ptsref,ind,xFE));

            testCase.verifyEqual(x,xFE,'AbsTol',testCase.tol,'function of the space');
        end

        function testProjectsCoarseFunction(testCase,hpClass)
            coarse = Mesh(struct('name','Square')).refine('uniform');
            marked4e = zeros(coarse.nrElems,1);
            marked4e(1:3:end) = 1;
            fine = coarse.refine(marked4e,'RGB');
            parent4e = fine.parent4e;
            degree4e = 4 + mod((1:coarse.nrElems)',3);
            feOld = hpClass(degree4e,coarse);
            fe = hpClass(degree4e(parent4e),fine);
            xOld = sin(1:feOld.allnrDoF)';
            xOld(feOld.nonDoFNodes) = 0;

            x = fe.project(@(pts,ptsref,ind)ProjectionTest.valueInParent(feOld,xOld,pts,parent4e(ind)));

            ProjectionTest.verifyValues(testCase,fe,x, ...
                @(z)ProjectionTest.valueInParent(feOld,xOld,fine.point4e(z),parent4e));
        end

        function testReducedArnoldWinther(testCase,reducedAWMesh)
            mesh = reducedAWMesh();
            fe = AW0(3,mesh);
            % cubic [s11 s22 s12] with the rigid motion div = (1 - y, x)
            f = @(z)[z(:,1) + z(:,2) + z(:,2).^3, 2*z(:,1) - z(:,2) + z(:,1).^3, ...
                (z(:,1).^2 - z(:,2).^2)/2 + z(:,1)];

            x = fe.project(f);

            testCase.verifyTrue(all(isfinite(x)),'finite coefficients');
            ProjectionTest.verifyValues(testCase,fe,x,@(z)f(mesh.point4e(z)));
        end

        function testBoundaryProjection(testCase,boundaryProjection)
            mesh = PatchTestCase.patchMesh(struct('name','Square','bdry','DNDN'));
            fe = boundaryProjection.space(mesh);
            f = ProjectionTest.field(boundaryProjection.field,boundaryProjection.degree,2);
            ed4Nb = mesh.ed4Nb;

            switch boundaryProjection.trace
                case 'normal'
                    x = fe.project(f);
                    val = fe.projectNbBoundary(@(z,n)sum(f(z).*n,2));
                    dofs = unique(fe.dof4ed(ed4Nb,:));
                case 'normalNormal'
                    x = fe.project(f);
                    ed4Bd = [mesh.ed4Db;ed4Nb];
                    val = fe.projectBoundary(ed4Bd,@(z,n)sum(f(z).*[n(:,1).^2,prod(n,2),prod(n,2),n(:,2).^2],2));
                    dofs = unique(fe.dof4ed(ed4Bd,:));
                case 'rowNormal'
                    % the rows of the matrix field belong to the two
                    % components, stored column by column
                    x = [fe.fe{1}.project(@(z)f(z)*[1 0 0 0;0 0 1 0]'); ...
                        fe.fe{2}.project(@(z)f(z)*[0 1 0 0;0 0 0 1]')];
                    val = fe.projectNbBoundary(@(z,n)[sum(f(z)*[1 0 0 0;0 0 1 0]'.*n,2), ...
                        sum(f(z)*[0 1 0 0;0 0 0 1]'.*n,2)]);
                    dofs = [unique(fe.fe{1}.dof4ed(ed4Nb,:)); ...
                        fe.fe{1}.nrDoF + unique(fe.fe{2}.dof4ed(ed4Nb,:))];
            end

            testCase.assertNotEmpty(dofs,'boundary degrees of freedom');
            testCase.verifyEqual(val(dofs),x(dofs),'AbsTol',testCase.tol,'boundary degrees of freedom');
            others = setdiff(1:fe.nrDoF,dofs);
            testCase.verifyEqual(val(others),zeros(numel(others),1),'other degrees of freedom');
        end

    end

