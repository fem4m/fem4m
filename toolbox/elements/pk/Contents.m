% PK  Lagrange, Crouzeix-Raviart, bubble, DG, and hp element families
%
%   Classes
%   B2k            -  Squared cubic bubble times Dubiner polynomials of degree k-6
%   Bk             -  Cubic bubble times Dubiner polynomials of degree k-3
%   CRk            -  Crouzeix-Raviart element of degree 1 or 3
%   CurlBk         -  Curls of the cubic bubble functions of Bk
%   CurlBRotk      -  Matrix bubble element space with curl rows
%   DGDk           -  Discontinuous Dubiner element of total degree k
%   DGDk3d         -  Discontinuous Dubiner element of degree k on tetrahedra
%   DGDkEdge       -  Discontinuous polynomial edge space of degree k
%   DGDkFace       -  Discontinuous Dubiner face space of total degree k
%   DGDkMatrix     -  Matrix-valued element built from DGDk or DGDk3d elements
%   DGDkVector     -  Vector-valued element built from DGDk or DGDk3d elements
%   DGHPk          -  hp-version discontinuous Pk element with elementwise degrees
%   DGPk           -  Discontinuous Lagrange Pk element of degree k
%   DGPk3d         -  Discontinuous Lagrange Pk element of degree k on tetrahedra
%   DGPkFace       -  Surface Pk space from the first-face basis of Pk3d
%   DGPkMatrix     -  Matrix-valued DGPk element built from DGPk elements
%   DGPkSymMatrix  -  Symmetric matrix-valued DGPk element
%   DGPkVector     -  Vector-valued DGPk element built from DGPk elements
%   HPk            -  hp-version Pk element with elementwise degrees
%   HPk3d          -  Hierarchical high-order H1 element on tetrahedra
%   PDGk           -  Discontinuous element of scaled monomials of degree k
%   PDGk3d         -  Discontinuous scaled monomial element of degree k on tetrahedra
%   PDGkMatrix     -  Matrix-valued PDGk element built from PDGk elements
%   PDGkSymMatrix  -  Symmetric matrix-valued PDGk element
%   PDGkVector     -  Vector-valued PDGk element built from PDGk elements
%   Pk             -  Continuous Lagrange Pk element of degree k
%   Pk3d           -  Continuous Lagrange Pk element of degree k on tetrahedra
%   PkVector       -  Vector-valued Pk element built from scalar Pk elements